from __future__ import annotations
import math
import hashlib
import statistics
import torch
import torch.nn.functional as F
from .core import cached_encode, cached_draw, native_moments, validate_cache_parity


def det_ce_per_image(mu, var, y, scale=1.0, clamp=50.0):
    """Elementwise version of production methods.det_bayesrt_mmrl.losses.det_jensen_ce."""
    if var.shape != mu.shape or mu.ndim != 2 or y.numel() != mu.shape[0]:
        raise ValueError('Moment/label shape mismatch')
    if not math.isfinite(float(scale)) or scale < 0:
        raise ValueError('Invalid scale')
    v = var.float().clamp_min(0)
    if clamp > 0:
        v = v.clamp_max(clamp)
    mean = mu.float()
    return torch.logsumexp(mean + .5 * scale * v, -1) - mean.gather(1, y[:, None]).squeeze(1)


def sampled_ce(c, r, y, alpha):
    """Shared draws: O, B, Main CE, Rep CE, Rep responsibility [S,B]."""
    if not 0 < alpha < 1:
        raise ValueError('Responsibility requires 0 < alpha < 1')
    idx = y[None, :, None].expand(c.shape[0], -1, 1)
    yc = F.log_softmax(c.float(), -1).gather(2, idx).squeeze(-1)
    yr = F.log_softmax(r.float(), -1).gather(2, idx).squeeze(-1)
    logmix = torch.logaddexp(yc+math.log(alpha), yr+math.log1p(-alpha))
    return -logmix, -(alpha*yc+(1-alpha)*yr), -yc, -yr, (yr+math.log1p(-alpha)-logmix).exp()


def _running_mean_and_m2(old_n, old_mean, old_m2, chunk):
    s = chunk.shape[0]
    current = chunk.double().mean(0)
    within = (chunk.double()-current).square().sum(0)
    if old_n == 0:
        return current, within
    delta = current-old_mean
    return old_mean + delta*s/(old_n+s), old_m2 + within + delta.square()*old_n*s/(old_n+s)


def posterior_summary(method, initial_state=None):
    model = method.model
    r, t = model.image_encoder.bayes_proj_rep, model.text_posterior
    if r is None or t is None:
        raise RuntimeError('Required asymmetric posterior missing')
    with torch.no_grad():
        tokens_t, tokens_v = model.representation_learner()
        result={'r_mean_fro': float(r.posterior_mean.float().norm()),
                'r_trace': float(r.expanded_posterior_sigma().float().square().sum()),
                't_trace': float(t.expanded_posterior_sigma().float().square().sum()),
                'visual_prompt_norm_mean': float(torch.stack([x.float().norm() for x in tokens_v]).mean()),
                'text_prompt_norm_mean': float(torch.stack([x.float().norm() for x in tokens_t]).mean()),
                'shared_token_norm': float(model.representation_learner.compound_rep_tokens.float().norm())}
        if initial_state is not None:
            # Paired *effective* prompts generated by the initial shared tokens +
            # modality/layer-specific mappings from the SAME native run.
            prefix='representation_learner.'
            if prefix+'compound_rep_tokens' not in initial_state:
                raise RuntimeError('Initialization checkpoint missing shared tokens')
            base=initial_state[prefix+'compound_rep_tokens'].to(tokens_v[0].device).float()
            for direction, learned in (('v',tokens_v),('t',tokens_t)):
                init=[]
                for i in range(len(learned)):
                    proj='compound_rep_tokens_r2'+direction+'proj.'+str(i)+'.'
                    w=initial_state[prefix+proj+'weight'].to(base.device).float()
                    b=initial_state[prefix+proj+'bias'].to(base.device).float()
                    init.append(F.linear(base,w,b))
                cos=[F.cosine_similarity(now.float().flatten()[None],
                      old.flatten()[None],dim=-1).item() for now,old in zip(learned,init)]
                result[('visual' if direction=='v' else 'text')+'_prompt_init_cos']=statistics.mean(cos)
                result[('visual' if direction=='v' else 'text')+'_prompt_init_cos_per_layer']=cos
        return result


def reference_diagnostics(trainer, loader, n_samples=1024, chunk=16, limit=None,
                          davi_params=None, vectors=False, parity=True):
    """E1/E2/E4. O,B MC on every method; D is DAVI only unless explicit counterfactual.

    Full-model forward parity checked on first batch. All metrics are image-weighted.
    E2 is NOT the native predictive NLL, which uses formal forward_eval.
    """
    method = trainer.method
    model = method.model
    alpha = float(method.cfg.BAYESRT_MMRL.ALPHA)
    if n_samples < 2 or chunk < 1:
        raise ValueError('Reference draws >=2 and chunk>=1 required')
    do_det = davi_params is not None
    if not 0 < alpha < 1:
        raise ValueError('This study expects 0<alpha<1')
    model.eval()
    rows, all_vectors, text_class_cos = [], [], None
    classes = method.num_classes
    input_digest=hashlib.sha256()
    with torch.no_grad():
        for bi, batch in enumerate(loader):
            if limit is not None and bi >= limit:
                break
            x = batch['img'].to(method.device)
            y = batch['label'].long().to(method.device)
            input_digest.update(x.detach().cpu().contiguous().numpy().tobytes())
            input_digest.update(y.detach().cpu().contiguous().numpy().tobytes())
            cache = cached_encode(model, x, classes)
            if bi == 0 and parity:
                validate_cache_parity(model, x, classes, cache)
            analytic = native_moments(model, x, method.cfg.BAYESRT_MMRL) if do_det else None
            if analytic is not None:
                mom = {k: analytic[k][..., :classes].float() for k in ('mu_main','var_main','mu_rep','var_rep')}
                scale, clamp = davi_params
                dmain = det_ce_per_image(mom['mu_main'], mom['var_main'], y, scale, clamp)
                drep = det_ce_per_image(mom['mu_rep'], mom['var_rep'], y, scale, clamp)
                dloss = alpha*dmain+(1-alpha)*drep
                from methods.det_bayesrt_mmrl.losses import det_jensen_ce
                native = (alpha*det_jensen_ce(mom['mu_main'],mom['var_main'],y,
                                               var_scale=scale,var_clamp=clamp)
                          +(1-alpha)*det_jensen_ce(mom['mu_rep'],mom['var_rep'],y,
                                                   var_scale=scale,var_clamp=clamp))
                if not torch.allclose(dloss.mean(),native,rtol=5e-5,atol=1e-4):
                    raise RuntimeError('DAVI per-image proxy disagrees with native det_jensen_ce')
            # streaming posterior MC, no O(S) logit caching
            n=0
            o = torch.zeros_like(y, dtype=torch.float64)
            b = o.clone(); mc = o.clone(); mr = o.clone(); rho = o.clone()
            m_c = m_r = m2_c = m2_r = None
            exp_c = exp_r = None
            p_c = torch.zeros((len(y), classes), device=y.device, dtype=torch.float64)
            p_r = torch.zeros_like(p_c)
            while n < n_samples:
                s = min(chunk, n_samples-n)
                c,r = cached_draw(cache,s)
                c=c.float();r=r.float()
                lo,lb,lmc,lmr,responsibility = sampled_ce(c,r,y,alpha)
                o += lo.double().sum(0)
                b += lb.double().sum(0)
                mc += lmc.double().sum(0)
                mr += lmr.double().sum(0)
                rho += responsibility.double().sum(0)
                p_c += F.softmax(c,-1).double().sum(0)
                p_r += F.softmax(r,-1).double().sum(0)
                m_c,m2_c = _running_mean_and_m2(n,m_c,m2_c,c)
                m_r,m2_r = _running_mean_and_m2(n,m_r,m2_r,r)
                ec=torch.logsumexp(c.double(),dim=0)
                er=torch.logsumexp(r.double(),dim=0)
                exp_c=ec if exp_c is None else torch.logaddexp(exp_c,ec)
                exp_r=er if exp_r is None else torch.logaddexp(exp_r,er)
                n += s
            o/=n; b/=n; mc/=n; mr/=n; rho/=n
            if float((b-o).min()) < -1.e-6:
                raise RuntimeError('First Jensen failed on shared draws')
            pm = p_c/n; pr = p_r/n
            # These are posterior predictive branch diagnostics, NOT static_logit.
            def exp_jensen(log_sum, mu):
                logmgf=log_sum-math.log(n)
                return torch.logsumexp(logmgf,-1)-mu.gather(1,y[:,None]).squeeze(1)
            jc=exp_jensen(exp_c,m_c);jr=exp_jensen(exp_r,m_r)
            empirical_j = alpha*jc+(1-alpha)*jr
            if float((empirical_j-b).min()) < -1.e-5:
                raise RuntimeError('Empirical Jensen positivity failed')
            # E4 representation: actual native posterior-mean projection features
            with torch.no_grad():
                image_clip = F.normalize(method.image_encoder_clip(x.type(method.dtype)).float(),-1)
                rep_mean = F.normalize(cache['rep'].float() @ model.image_encoder.bayes_proj_rep.posterior_mean.float(),-1)
                image_sim = F.cosine_similarity(rep_mean,image_clip,-1)
                text_mean = F.normalize(cache['eot'].float() @ model.text_posterior.posterior_mean.float(),-1)
                text_ref = F.normalize(method.text_features_clip[:classes].to(y.device).float(),-1)
                if bi==0:
                    text_class_cos=F.cosine_similarity(text_mean,text_ref,-1).cpu().tolist()
            # Match production single-branch output: log(mean_s softmax(z_s)).
            # NOT the argmax/scale of mean sampled logits.
            rep_logp=pr.clamp_min(1e-12).log()
            rep_margin=rep_logp.gather(1,y[:,None]).squeeze(1)-rep_logp.masked_fill(
                F.one_hot(y,classes).bool(),float('-inf')).max(-1).values
            for i in range(len(y)):
                z = dict(original_nll=float(o[i]), branch_nll=float(b[i]),
                    gap1=float(b[i]-o[i]), main_mc_ce=float(mc[i]), rep_mc_ce=float(mr[i]),
                    rho_rep=float(rho[i]), main_correct=int(pm[i].argmax()==y[i]),
                    rep_correct=int(pr[i].argmax()==y[i]), rep_margin=float(rep_margin[i]),
                    visual_clip_cos=float(image_sim[i]), sampled_var=float(
                        (alpha*m2_c[i].mean()+(1-alpha)*m2_r[i].mean())/n),
                    empirical_jensen_gap=float(empirical_j[i]-b[i]))
                if do_det:
                    gmain = det_ce_per_image(m_c[i:i+1].float(),(m2_c[i:i+1]/n).float(),y[i:i+1], 1.0, 0.0)
                    grep = det_ce_per_image(m_r[i:i+1].float(),(m2_r[i:i+1]/n).float(),y[i:i+1], 1.0, 0.0)
                    empirical_g=float(alpha*gmain+(1-alpha)*grep)
                    z.update(det_nll=float(dloss[i]),gap2=float(dloss[i]-b[i]),
                             abs_gap2=float((dloss[i]-b[i]).abs()),
                             mean_mae=float(alpha*(mom['mu_main'][i]-m_c[i]).abs().mean()+
                                            (1-alpha)*(mom['mu_rep'][i]-m_r[i]).abs().mean()),
                             var_mae=float(alpha*(mom['var_main'][i]-m2_c[i]/n).abs().mean()+
                                           (1-alpha)*(mom['var_rep'][i]-m2_r[i]/n).abs().mean()),
                             gaussian_mgf_error=empirical_g-float(empirical_j[i]),
                             propagation_and_native_variance_error=float(dloss[i])-empirical_g,
                             main_abs_det_gap=float((dmain[i]-mc[i]).abs()),
                             rep_abs_det_gap=float((drep[i]-mr[i]).abs()),
                             main_sampled_var=float(m2_c[i].mean()/n),
                             rep_sampled_var=float(m2_r[i].mean()/n))
                rows.append(z)
                if vectors and do_det:
                    all_vectors.append({k:val[i].detach().cpu().float().tolist() for k,val in {
                        'mu_main_mc':m_c,'var_main_mc':m2_c/n,'mu_rep_mc':m_r,'var_rep_mc':m2_r/n,
                        'mu_main_det':mom['mu_main'],'var_main_det':mom['var_main'],
                        'mu_rep_det':mom['mu_rep'],'var_rep_det':mom['var_rep']}.items()})
    if not rows:
        raise RuntimeError('No reference examples')
    summary = {k:statistics.mean(row[k] for row in rows) for k in rows[0]}
    summary.update({'n_images':len(rows),'s_ref':n_samples,
                    'input_sha256':input_digest.hexdigest(),
                    'rep_margin_type':'posterior_predictive_log_probability',
                    'rho_rep_median':statistics.median(r['rho_rep'] for r in rows),
                    'rep_margin_median':statistics.median(r['rep_margin'] for r in rows),
                    'main_predictive_acc':100*summary['main_correct'],
                    'rep_predictive_acc':100*summary['rep_correct'],
                    'text_clip_cos_mean':statistics.mean(text_class_cos),
                    'text_clip_cos_per_class':text_class_cos})
    if do_det:
        summary['gap_identity_abs']=abs((summary['gap1']+summary['gap2'])-
                                        (summary['det_nll']-summary['original_nll']))
        if summary['gap_identity_abs'] > 1e-5:
            raise RuntimeError('Objective gap telescoping failed')
        from methods.det_bayesrt_mmrl.losses import det_jensen_ce
        # First-batch identical production CE parity is checked in a separate GPU smoke test.
        summary['davi_var_scale']=scale
        summary['davi_var_clamp']=clamp
    return summary, rows, all_vectors


def native_predictions(trainer, split='test', limit=None):
    """Formal FS forward_eval + select_eval_logits + repository calibration report.

    Deliberately separate from high-S E2 reference. N_MC_TEST comes from YAML.
    """
    from core.types import EvalContext
    from evaluation.metrics import build_classification_calibration_report
    method=trainer.method
    if split=='test':
        loader=trainer.test_loader
    elif split=='val':
        loader=trainer.val_loader
        if loader is None:
            raise RuntimeError('No validation loader')
    else:
        raise ValueError(split)
    ctx=EvalContext(protocol='FS', dataset_name=trainer.cfg.DATASET.NAME,
                    split=split, subsample_classes='all',phase=trainer.cfg.PROTOCOL.PHASE)
    routed=[];labels=[];mains=[];reps=[]
    trainer.method.model.eval()
    with torch.no_grad():
        for bi,batch in enumerate(loader):
            if limit is not None and bi>=limit:
                break
            image=batch['img'].to(method.device)
            label=batch['label'].to(method.device).long()
            out=method.forward_eval({'img':image,'label':label},ctx)
            routed.append(method.select_eval_logits(out,ctx).detach().cpu().float())
            mains.append(out.logits.detach().cpu().float())
            reps.append(out.aux_logits['rep'].detach().cpu().float())
            labels.append(label.detach().cpu())
    if not labels:
        raise RuntimeError('Formal validation/test loader empty')
    y=torch.cat(labels)
    z=torch.cat(routed)
    main=torch.cat(mains);rep=torch.cat(reps)
    report=build_classification_calibration_report(logits=z,labels=y,n_bins=10)
    return {'metrics':report['metrics'],
            'n_images':len(y),
            'main_accuracy':100*float((main.argmax(-1)==y).float().mean()),
            'rep_accuracy':100*float((rep.argmax(-1)==y).float().mean()),
            'rep_predictive_nll':float(F.cross_entropy(rep,y)),
            'main_predictive_nll':float(F.cross_entropy(main,y)),
            'fusion_accuracy':100*float((z.argmax(-1)==y).float().mean()),
            'eval_fusion_variant':str(method.cfg.BAYESRT_MMRL.EVAL_FUSION_VARIANT),
            'n_mc_test':int(method.n_mc_test),
            'eval_use_posterior_mean':bool(method.eval_use_posterior_mean)}


def gradient_quality(trainer,batch,reference_samples=512,chunk=8,repeats=5,
                     sizes=(1,5,10,50)):
    """E3: Φ classification gradients, high-S reference in independent streams.

    Recompute CLIP encoder per MC microchunk, avoid retaining S_ref computation graph.
    The no-sampling DAVI gradient uses *native* forwarded moments.
    """
    from .core import cached_draw, cached_encode, native_moments
    method=trainer.method;model=method.model;cfg=method.cfg.BAYESRT_MMRL
    x=batch['img'].to(method.device);y=batch['label'].long().to(method.device)
    alpha=float(cfg.ALPHA)
    params=[p for name,p in model.named_parameters()
            if name.startswith('representation_learner.') and p.requires_grad]
    if not params:raise RuntimeError('No trainable representation_learner parameters')
    model.eval()
    def vector(gs):
        return torch.cat([(g.detach().float() if g is not None else torch.zeros_like(p).float()).flatten()
                          for p,g in zip(params,gs)])
    def det_grad():
        data=native_moments(model,x,cfg)
        varargs=(float(cfg.DET_VAR_SCALE),float(cfg.DET_VAR_CLAMP))
        value=alpha*det_ce_per_image(data['mu_main'],data['var_main'],y,*varargs).mean()+\
             (1-alpha)*det_ce_per_image(data['mu_rep'],data['var_rep'],y,*varargs).mean()
        return vector(torch.autograd.grad(value,params,allow_unused=True))
    def mc_grad(s):
        acc=None;n=0
        while n<s:
            k=min(chunk,s-n)
            cache=cached_encode(model,x,method.num_classes)
            m,r=cached_draw(cache,k)
            loss=sampled_ce(m,r,y,alpha)[1].mean()
            grads=vector(torch.autograd.grad(loss,params,allow_unused=True))
            acc=grads*k if acc is None else acc+grads*k
            n+=k
        return acc/s
    devices=[x.device.index if x.device.index is not None else torch.cuda.current_device()] if x.is_cuda else []
    with torch.enable_grad(), torch.random.fork_rng(devices=devices):
        torch.manual_seed(71021)
        ref=mc_grad(reference_samples)
        torch.manual_seed(71022)
        ref2=mc_grad(reference_samples)
        if not bool(torch.isfinite(ref).all()) or float(ref.norm()) < 1e-12:
            raise RuntimeError('Reference gradient degenerate')
        def quality(g):
            return {'cosine':float(F.cosine_similarity(g[None],ref[None])),
                    'relative_error':float((g-ref).norm()/ref.norm())}
        result={'reference_norm':float(ref.norm()),'reference_samples':reference_samples,
                'reference_repeat_quality':quality(ref2),
                'reference_stable':(quality(ref2)['cosine']>=0.95 and quality(ref2)['relative_error']<=0.25),
                'davi':quality(det_grad()),'curve':[],'phi_numel':ref.numel(),
                'data_term_only':True}
        for s in sizes:
            for repeat in range(repeats):
                torch.manual_seed(81000+1000*s+repeat)
                result['curve'].append({'samples':s,'repeat':repeat,**quality(mc_grad(s))})
    return result
